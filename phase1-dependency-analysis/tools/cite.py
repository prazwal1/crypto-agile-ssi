#!/usr/bin/env python3
"""Extract cited source lines from the pinned clones into one Markdown file, so every
file:line reference in a write-up can be checked against the exact code.

Usage: python3 cite.py <citations.tsv> <out.md>
citations.tsv columns: id, repo, path (relative to the repo), start line, end line, note
The commit of each repo is read from manifest.tsv and printed with every excerpt.
"""
import csv, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
manifest = {}
with open(os.path.join(root, 'manifest.tsv')) as f:
    for row in csv.reader(f, delimiter='\t'):
        if row: manifest[row[0]] = (row[1], row[2])
rows = [r for r in csv.reader(open(sys.argv[1]), delimiter='\t') if r and not r[0].startswith('#')]
out = ['# Source excerpts', '', f'Generated by `tools/cite.py` from `{os.path.basename(sys.argv[1])}`. Line numbers are 1-based and refer to the pinned commit shown.', '']
for cid, repo, path, a, b, note in rows:
    a, b = int(a), int(b); tag, sha = manifest.get(repo, ('?', '?'))
    lines = open(os.path.join(root, 'repos', repo, path), encoding='utf-8', errors='replace').read().splitlines()
    out += [f'## {cid}: {note}', '', f'`{repo}` {tag} (`{sha[:12]}`) `{path}` lines {a} to {b}', '', '```']
    out += [f'{i:>5}  {lines[i-1]}' for i in range(a, min(b, len(lines)) + 1)]
    out += ['```', '']
open(sys.argv[2], 'w').write('\n'.join(out))
print('wrote', sys.argv[2], len(rows), 'excerpts')
